"""Write docs/legal/REVIEW_PACKET.md: what a legal reviewer needs in one place, kept current from the registries.

Usage: python3 tools/generate_review_packet.py          (writes the file)
       python3 tools/generate_review_packet.py --check  (fails if the file is out of date)

It only gathers facts (what ships, under which licence, from where, with which hash, and what is still unresolved). It does not
approve anything: approving an asset, clearing the name or settling the licence expression is a decision for a person (ideally
a qualified reviewer), recorded in `provenance/assets.json` and in the release notes.
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
TARGET = ROOT / "docs" / "legal" / "REVIEW_PACKET.md"


def render() -> str:
    assets = json.loads((ROOT / "provenance" / "assets.json").read_text(encoding="utf-8"))["assets"]
    sources = json.loads((ROOT / "provenance" / "source-licenses.json").read_text(encoding="utf-8"))
    shipped = sorted((a for a in assets if a["path"].startswith("web/public/")), key=lambda a: a["path"])
    waiting = [a for a in shipped if a["status"] != "approved"]
    lines = [
        "<!-- SPDX-License-Identifier: GPL-2.0-or-later -->",
        "<!-- Generated by tools/generate_review_packet.py from the registries in provenance/: edit those, not this file. -->",
        "",
        "# Legal review packet",
        "",
        "Everything a reviewer needs to decide whether OpenSynd's web release may be called cleared. It gathers facts; it approves",
        "nothing. Approval is a person's decision (ideally a qualified reviewer's), recorded in `provenance/assets.json` and in the",
        "release notes (see `docs/RELEASING.md`, \"The legal gate\").",
        "",
        "## 1. What the web release ships",
        "",
        f"- **Code**: every `.js`, `.css` and `.html` file, GPL-2.0-or-later (SPDX notice in each; checked by CI).",
        "- **Content**: `open-content/packs/developer`, CC0-1.0, written for this project (no original *Syndicate* material).",
        f"- **Registered assets**: {len(shipped)} files under `web/public/assets/`, of which **{len(waiting)} are not yet approved**.",
        "- **Nothing** from the original game, and nothing from `data/` or `icon/` (excluded or quarantined, not built into the site).",
        "",
        "| File | Licence | Maker | Source | Status | SHA-256 (first 12) |",
        "| --- | --- | --- | --- | --- | --- |",
    ]
    for asset in shipped:
        name = asset["path"].removeprefix("web/public/assets/")
        lines.append(
            f"| `{name}` | {asset['license']} | {asset.get('creator', 'UNKNOWN')} | {asset.get('source', 'NOASSERTION')} | "
            f"{asset['status']} | `{asset['sha256'][:12]}` |"
        )
    lines += [
        "",
        "## 2. Questions for the reviewer",
        "",
        "1. **Assets.** Is each source and licence above adequately evidenced (a page that states the licence, the author, the date)? "
        "Note the music track offered under `GPL-3.0-only OR CC-BY-SA-3.0`: the project uses it under CC-BY-SA-3.0 with attribution "
        "(see the About box); is that the right reading, and is the share-alike requirement satisfied by how it is shipped as a "
        "separate audio file?",
        "2. **Licence expression.** The inherited FreeSynd tree is audited as GPL-2.0-or-later; the web code is new work under the same "
        "terms. Is any inherited file GPL-2.0-only? (`docs/legal/IP_AUDIT.md`, \"Open questions\".)",
        "3. **Name.** \"OpenSynd\" is the final name (the project owner's decision). No formal trademark search has been done and the "
        "project claims the name is neither registered nor cleared. Is that posture acceptable for a free hobby game, and what would a "
        "search against *Syndicate* and FreeSynd be needed for? (`TRADEMARKS.md`.)",
        "4. **Fan-game posture.** The game takes rules and values from the FreeSynd source (GPL) but no art, sound, text or maps from "
        "the original game. Is the public statement of that in the README and About box sufficient?",
        "5. **Unresolved source files** (not part of the web build): see section 3.",
        "",
        "## 3. Unresolved source files",
        "",
        "These legacy engine files have no usable licence notice. None is built into or shipped with the web game; each is pinned by "
        "hash so any change needs a renewed review.",
        "",
    ]
    for item in sources["unresolved"]:
        lines.append(f"- `{item['path']}` (`{item['sha256'][:12]}`): {item['notes']}")
    lines += [
        "",
        "## 4. What the project already does",
        "",
        "- CI fails on an unregistered asset, a hash mismatch, an unknown source licence or a dependency outside the accepted licences.",
        "- The release tool (`tools/make_release.py`) refuses to make a *cleared* release while any shipped asset is not approved, and "
        "writes `cleared: false` into `asset-bom.json` otherwise.",
        "- The site makes no request to any other site and keeps no data about visitors (`PRIVACY.md`; checked by a browser test).",
        "",
    ]
    return "\n".join(lines)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    text = render()
    if args.check:
        if not TARGET.is_file() or TARGET.read_text(encoding="utf-8") != text:
            print("review packet: ERROR: docs/legal/REVIEW_PACKET.md is out of date; run tools/generate_review_packet.py", file=sys.stderr)
            return 1
        print("review packet: up to date")
        return 0
    TARGET.write_text(text, encoding="utf-8")
    print(f"review packet: wrote {TARGET.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
