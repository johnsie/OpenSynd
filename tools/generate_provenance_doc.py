"""Write PROVENANCE.md, a readable summary of provenance/assets.json (the machine-checked registry).

Run `python3 tools/generate_provenance_doc.py` after changing the registry.
"""

from __future__ import annotations

import json
from collections import Counter, defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
GROUPS = [
    ("Character pictures (sprite sheets)", {"derived-sprite-sheet"}),
    ("The 3D model they are drawn from", {"third-party-art-source"}),
    ("Music", {"music"}),
    ("Inherited from FreeSynd, not used by the browser game", {
        "legacy-localization", "legacy-branding", "legacy-audio", "legacy-artwork", "legacy-game-data",
        "original-game-compatibility",
    }),
]


def main() -> None:
    registry = json.loads((ROOT / "provenance/assets.json").read_text(encoding="utf-8"))
    assets = registry["assets"]
    by_status = Counter(asset["status"] for asset in assets)
    lines = [
        "<!-- SPDX-License-Identifier: GPL-2.0-or-later -->",
        "<!-- Generated by tools/generate_provenance_doc.py from provenance/assets.json: edit the registry, not this file. -->",
        "",
        "# Provenance",
        "",
        "Where everything in this repository that is not source code came from: pictures, sounds, models and data. This is a",
        "hobby project for my own use, but I still want to be able to say where every file came from and what licence it is",
        "under. The exact, machine-checked record is [provenance/assets.json](provenance/assets.json) (one entry per file, with",
        "its SHA-256 digest); this page is the readable version of it. The rules are in [ASSET_POLICY.md](ASSET_POLICY.md) and",
        "the overview is in the [README](README.md).",
        "",
        "## The short version",
        "",
        "- **Code** is GPL-2.0-or-later (FreeSynd's licence). **Game content** I wrote (the maps, missions, units, equipment and",
        "  text in `open-content/`) is CC0-1.0, dedicated to the public domain.",
        "- **Nothing the browser game uses comes from other games:** no graphics, sounds, music, maps,",
        "  missions or data files. (What FreeSynd left in the repository is a separate matter, covered below.)",
        "- The **character pictures** are rendered by my own scripts from one free (CC0) 3D model by Quaternius.",
        "- The **music** is by two free-music authors, credited below.",
        "- Files **inherited from FreeSynd** (old text, branding, sounds, data tables) are still in the repository for the old C++",
        "  engine, are **not used** by the browser game, and are marked `quarantined` or `excluded`.",
        "",
        "## Honest caveats",
        "",
        f"- The registry has **{by_status['quarantined']} quarantined, {by_status['excluded']} excluded and "
        f"{by_status['approved']} approved** entries.",
        "  \"Approved\" is only given after a named person reviews a file, and that has not happened: I did the intake",
        "  checking with an AI assistant, which is not a legal review.",
        "- Anything marked `NOASSERTION` is inherited and its licence is **unknown**; I am not relying on it.",
        "",
    ]
    for title, classes in GROUPS:
        group = [asset for asset in assets if asset["classification"] in classes]
        if not group:
            continue
        lines += [f"## {title}", ""]
        if classes == {"derived-sprite-sheet"}:
            lines += [
                f"{len(group)} sheets in `web/public/assets/sprites/`, made by `web/tools/render-sprites.mjs` from the model below",
                "(clothes, hair, boots and gear are generated shapes added to its skeleton by `web/tools/render.html`).",
                "Licence CC0-1.0; creator credited as Quaternius for the model, with rendering and styling by the project's contributors.",
                "",
            ]
            continue
        grouped: dict[tuple, list[dict]] = defaultdict(list)
        for asset in group:
            grouped[(asset["creator"], asset["license"], asset["source"])].append(asset)
        for (creator, licence, source), items in grouped.items():
            where = source if source.startswith("http") else f"{source}"
            lines.append(f"- **{creator}**, licence `{licence}`, source: {where}")
            for item in items[:8]:
                lines.append(f"  - `{item['path']}` ({item['status']})")
            if len(items) > 8:
                lines.append(f"  - and {len(items) - 8} more")
        lines.append("")
    lines += [
        "## Music licences in plain words",
        "",
        "\"Electric Stream\" (Alexander Ehlers) is CC0. \"The Core\" (p0ss) is offered under GPL-3.0-only **or** CC-BY-SA-3.0, so it",
        "needs attribution, which is why it is credited in the README.",
        "",
        "## Keeping this up to date",
        "",
        "```sh",
        "python3 tools/check_provenance.py            # checks the registry against the files on disk",
        "python3 tools/generate_provenance_doc.py     # rewrites this page from the registry",
        "```",
        "",
    ]
    (ROOT / "PROVENANCE.md").write_text("\n".join(lines), encoding="utf-8")


if __name__ == "__main__":
    main()
